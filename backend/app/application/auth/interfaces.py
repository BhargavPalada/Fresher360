"""Application-layer interfaces (Protocols).

These define the contracts that infrastructure implementations must satisfy.
The application/domain layers import these — never the concrete implementations.
"""
from __future__ import annotations

import uuid
from typing import Any, Protocol, runtime_checkable

from app.domain.entities.user import User
from app.domain.enums.user_role import UserRole


@runtime_checkable
class IUserRepository(Protocol):
    async def get_by_email(self, email: str) -> User | None: ...
    async def get_by_id(self, user_id: uuid.UUID) -> User | None: ...
    async def create(self, user: User) -> User: ...
    async def email_exists(self, email: str) -> bool: ...
    async def get_all(self) -> list[User]: ...
    async def update_role(self, user_id: uuid.UUID, role: UserRole) -> User | None: ...


@runtime_checkable
class IPasswordHasher(Protocol):
    def hash(self, plain_password: str) -> str: ...
    def verify(self, plain_password: str, hashed_password: str) -> bool: ...


@runtime_checkable
class IJWTService(Protocol):
    def encode_access_token(self, user_id: uuid.UUID, role: UserRole) -> str: ...
    def encode_refresh_token(self, user_id: uuid.UUID) -> str: ...
    def decode_access_token(self, token: str) -> dict[str, Any]: ...
    def decode_refresh_token(self, token: str) -> dict[str, Any]: ...
